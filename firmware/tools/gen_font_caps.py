#!/usr/bin/env python3
"""Generate src/font_caps.h: a condensed caps-only 7-row LED font.
Edit the glyph art below, then run: python3 tools/gen_font_caps.py"""
import pathlib

G = {}
def g(ch, *rows):
    assert len(rows) == 7, ch
    w = len(rows[0]); assert all(len(r) == w for r in rows), ch
    G[ch] = rows

g(' ', '..', '..', '..', '..', '..', '..', '..')
g('A', '.#.', '#.#', '#.#', '###', '#.#', '#.#', '#.#')
g('B', '##.', '#.#', '#.#', '##.', '#.#', '#.#', '##.')
g('C', '.##', '#..', '#..', '#..', '#..', '#..', '.##')
g('D', '##.', '#.#', '#.#', '#.#', '#.#', '#.#', '##.')
g('E', '###', '#..', '#..', '##.', '#..', '#..', '###')
g('F', '###', '#..', '#..', '##.', '#..', '#..', '#..')
g('G', '.##', '#..', '#..', '#.#', '#.#', '#.#', '.##')
g('H', '#.#', '#.#', '#.#', '###', '#.#', '#.#', '#.#')
g('I', '###', '.#.', '.#.', '.#.', '.#.', '.#.', '###')
g('J', '..#', '..#', '..#', '..#', '..#', '#.#', '.#.')
g('K', '#.#', '#.#', '##.', '#..', '##.', '#.#', '#.#')
g('L', '#..', '#..', '#..', '#..', '#..', '#..', '###')
g('M', '#...#', '##.##', '#.#.#', '#.#.#', '#...#', '#...#', '#...#')
g('N', '#..#', '##.#', '##.#', '#.##', '#.##', '#..#', '#..#')
g('O', '.#.', '#.#', '#.#', '#.#', '#.#', '#.#', '.#.')
g('P', '##.', '#.#', '#.#', '##.', '#..', '#..', '#..')
g('Q', '.#.', '#.#', '#.#', '#.#', '#.#', '##.', '.##')
g('R', '##.', '#.#', '#.#', '##.', '#.#', '#.#', '#.#')
g('S', '.##', '#..', '#..', '.#.', '..#', '..#', '##.')
g('T', '###', '.#.', '.#.', '.#.', '.#.', '.#.', '.#.')
g('U', '#.#', '#.#', '#.#', '#.#', '#.#', '#.#', '###')
g('V', '#.#', '#.#', '#.#', '#.#', '#.#', '.#.', '.#.')
g('W', '#...#', '#...#', '#...#', '#.#.#', '#.#.#', '##.##', '#...#')
g('X', '#.#', '#.#', '#.#', '.#.', '#.#', '#.#', '#.#')
g('Y', '#.#', '#.#', '#.#', '.#.', '.#.', '.#.', '.#.')
g('Z', '###', '..#', '..#', '.#.', '#..', '#..', '###')
g('0', '.#.', '#.#', '#.#', '#.#', '#.#', '#.#', '.#.')
g('1', '.#', '##', '.#', '.#', '.#', '.#', '.#')
g('2', '##.', '..#', '..#', '.#.', '#..', '#..', '###')
g('3', '##.', '..#', '..#', '.#.', '..#', '..#', '##.')
g('4', '#.#', '#.#', '#.#', '###', '..#', '..#', '..#')
g('5', '###', '#..', '#..', '##.', '..#', '..#', '##.')
g('6', '.##', '#..', '#..', '##.', '#.#', '#.#', '.#.')
g('7', '###', '..#', '..#', '.#.', '.#.', '.#.', '.#.')
g('8', '.#.', '#.#', '#.#', '.#.', '#.#', '#.#', '.#.')
g('9', '.#.', '#.#', '#.#', '.##', '..#', '..#', '##.')
g('.', '.', '.', '.', '.', '.', '.', '#')
g(',', '.', '.', '.', '.', '.', '#', '#')
g(':', '.', '.', '#', '.', '.', '#', '.')
g(';', '.', '.', '#', '.', '.', '#', '#')
g("'", '#', '#', '.', '.', '.', '.', '.')
g('`', '#', '#', '.', '.', '.', '.', '.')
g('"', '#.#', '#.#', '...', '...', '...', '...', '...')
g('!', '#', '#', '#', '#', '#', '.', '#')
g('?', '##.', '..#', '..#', '.#.', '.#.', '...', '.#.')
g('-', '..', '..', '..', '##', '..', '..', '..')
g('_', '###', '...', '...', '...', '...', '...', '###')  # replaced below
G['_'] = ('...', '...', '...', '...', '...', '...', '###')
g('+', '...', '.#.', '.#.', '###', '.#.', '.#.', '...')
g('=', '...', '...', '###', '...', '###', '...', '...')
g('*', '...', '#.#', '.#.', '#.#', '...', '...', '...')
g('/', '..#', '..#', '.#.', '.#.', '.#.', '#..', '#..')
g('\\', '#..', '#..', '.#.', '.#.', '.#.', '..#', '..#')
g('|', '#', '#', '#', '#', '#', '#', '#')
g('(', '.#', '#.', '#.', '#.', '#.', '#.', '.#')
g(')', '#.', '.#', '.#', '.#', '.#', '.#', '#.')
g('[', '##', '#.', '#.', '#.', '#.', '#.', '##')
g(']', '##', '.#', '.#', '.#', '.#', '.#', '##')
g('{', '.#', '#.', '#.', '##', '#.', '#.', '.#')
g('}', '#.', '.#', '.#', '##', '.#', '.#', '#.')
g('<', '...', '..#', '.#.', '#..', '.#.', '..#', '...')
g('>', '...', '#..', '.#.', '..#', '.#.', '#..', '...')
g('&', '.#..', '#.#.', '#.#.', '.#..', '#.##', '#.#.', '.#.#')
g('#', '.#.#.', '.#.#.', '#####', '.#.#.', '#####', '.#.#.', '.#.#.')
g('%', '#...#', '#..#.', '..#..', '..#..', '.#...', '#..#.', '...#.')
G['%'] = ('##..#', '##.#.', '..#..', '..#..', '.#...', '#.##.', '..##.')
g('@', '.##.', '#..#', '#.##', '#.##', '#.#.', '#...', '.##.')
g('$', '.#.', '.##', '#..', '.#.', '..#', '##.', '.#.')
g('^', '.#.', '#.#', '...', '...', '...', '...', '...')
g('~', '....', '....', '.#.#', '#.#.', '....', '....', '....')
g('\x7f', '...', '...', '.#.', '###', '.#.', '...', '...')  # separator diamond

cols, index = [], []
for code in range(0x20, 0x80):
    ch = chr(code)
    if 'a' <= ch <= 'z': ch = ch.upper()
    rows = G.get(ch, G['?'])
    w = len(rows[0])
    index.append((len(cols), w))
    for x in range(w):
        b = 0
        for y in range(7):
            if rows[y][x] == '#': b |= 1 << y
        cols.append(b)

out = ['#pragma once', '#include <stdint.h>',
       '// GENERATED by tools/gen_font_caps.py - edit the glyph art there, not here.',
       '// Condensed caps-only 7-row font, ASCII 0x20..0x7F (lowercase maps to caps).',
       '// Column-major, bit0 = top row. 0x7F = separator diamond.',
       'static const uint8_t FONT_CAPS_COLS[] = {']
for i in range(0, len(cols), 16):
    out.append('  ' + ','.join(f'0x{c:02X}' for c in cols[i:i+16]) + ',')
out.append('};')
out.append('static const uint16_t FONT_CAPS_INDEX[96][2] = {  // {first column, width}')
for i in range(0, 96, 8):
    out.append('  ' + ','.join(f'{{{o},{w}}}' for o, w in index[i:i+8]) + ',')
out.append('};')
p = pathlib.Path(__file__).resolve().parent.parent / 'src' / 'font_caps.h'
p.write_text('\n'.join(out) + '\n')
print('wrote', p, len(cols), 'columns')
